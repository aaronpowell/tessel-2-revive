#!/usr/bin/env bash
# extract-node-payload.sh — build the production Node/Tessel runtime payload for
# the 25.12 image, self-contained from the Tessel factory RESTORE image.
#
# WHY THIS EXISTS
# ---------------
# The production image needs Node on-device so `t2 run`/`t2 push` execute JS. The
# original Tessel firmware shipped Node built for MIPS soft-float. Two paths were
# scoped and rejected:
#   * Build Node 8.11.3 from source on the 25.12 toolchain — NO-GO: 25.12 defaults
#     to gcc-14.3.0 but Node 8's bundled V8 6.2 needs gcc<=8; py2-only gyp/configure;
#     openssl-3 vs --shared-openssl.
#   * Lift the factory /usr/bin/node binary as-is — the factory image ships Node
#     **v4.2.1** linked against **uClibc** (interp /lib/ld-uClibc.so.0, libc.so.0),
#     because 15.05 Chaos Calmer used uClibc. 25.12 is musl. A uClibc ELF cannot run
#     on a musl rootfs against the musl loader.
#
# THE APPROACH (implemented here)
# -------------------------------
# Lift the factory Node 4.2.1 together with its ENTIRE uClibc dependency closure,
# and ISOLATE it from the musl rootfs so the two C libraries never mix:
#   * node's PT_INTERP stays /lib/ld-uClibc.so.0 (patchelf can't edit it — the
#     factory ELFs are sstripped, no section headers), so the uClibc loader is
#     placed at /lib/ld-uClibc.so.0. Its soname differs from musl's
#     ld-musl-mipsel-sf.so.1, so there is zero collision in /lib.
#   * the rest of the closure lives in /opt/tessel/lib. A /usr/bin/node wrapper
#     sets LD_LIBRARY_PATH=/opt/tessel/lib, which uClibc's ld.so searches BEFORE
#     /lib:/usr/lib — so the two sonames that also exist as musl builds in
#     /usr/lib (libstdc++.so.6, libz.so.1) resolve to the uClibc copies, not the
#     musl ones. No overwrite of any stock rootfs lib.
#   * the wrapper also sets NODE_PATH=/usr/lib/node: Node derives its legacy global
#     module dir from execPath (/opt/tessel/bin/node -> /opt/tessel/lib/node), so
#     without NODE_PATH `require('tessel')` would miss /usr/lib/node/tessel.js.
#
# OUTPUT
# ------
# A rootfs-rooted tarball consumed by build.sh (TESSEL_PROD=1), which untars it
# into the OpenWrt files/ overlay. The tarball is intentionally NOT committed
# (large binaries); it is regenerated by this script from the factory tarball.
#
# USAGE (inside the build container, where the staging tools + /artifacts exist):
#   docker compose run --rm --entrypoint bash build -lc \
#     "bash /overlay-scripts/extract-node-payload.sh"
# It needs:
#   * the factory tarball at $FACTORY (default /artifacts/factory_new_build_next.tar.gz)
#   * a built 25.12 tree for unsquashfs4 + the target readelf (default under /work)
# and writes $OUT (default /artifacts/tessel-node-payload.tar.gz).
set -euo pipefail

FACTORY="${FACTORY:-/artifacts/factory_new_build_next.tar.gz}"
OUT="${OUT:-/artifacts/tessel-node-payload.tar.gz}"
TREE="${TREE:-/work/openwrt-v25.12.5}"
WORK="${WORK:-/work/prod-node}"

RE="$(ls "$TREE"/staging_dir/toolchain-*/bin/mipsel-openwrt-linux-readelf 2>/dev/null | head -1)"
UNSQ="$TREE/staging_dir/host/bin/unsquashfs4"
[[ -f "$FACTORY" ]] || { echo "ERROR: factory tarball not found: $FACTORY" >&2; exit 1; }
[[ -x "$RE"      ]] || { echo "ERROR: target readelf not found under $TREE (build 25.12 first)" >&2; exit 1; }
[[ -x "$UNSQ"    ]] || { echo "ERROR: unsquashfs4 not found under $TREE (build 25.12 first)" >&2; exit 1; }

needed() { "$RE" -d "$1" 2>/dev/null | awk '/NEEDED/{gsub(/[][]/,"",$5); print $5}'; }

echo "==> extracting factory rootfs squashfs"
rm -rf "$WORK"; mkdir -p "$WORK/fac"
tar xzf "$FACTORY" -C "$WORK/fac"
BIN="$(find "$WORK/fac" -name '*sysupgrade.bin' | head -1)"
OFF="$(python3 -c "print(open('$BIN','rb').read().find(b'hsqs'))")"
echo "    squashfs (hsqs) at offset $OFF in $(basename "$BIN")"
dd if="$BIN" of="$WORK/root.sqsh" bs=1 skip="$OFF" status=none
R="$WORK/facroot"; "$UNSQ" -d "$R" "$WORK/root.sqsh" >/dev/null 2>&1

echo "==> collecting node + transitive uClibc closure"
find_lib() { for d in "$R"/lib "$R"/usr/lib; do p="$d/$1"; [[ -e "$p" ]] && { readlink -f "$p"; return; }; done; }
OUTD="$WORK/opt/tessel"; rm -rf "$WORK/opt"; mkdir -p "$OUTD/bin" "$OUTD/lib"
cp "$R/usr/bin/node" "$OUTD/bin/node"
declare -A seen
INTERP_SO="$(basename "$("$RE" -l "$OUTD/bin/node" | awk -F': ' '/program interpreter/{gsub(/].*/,"",$2);print $2}')")"
queue="$(needed "$OUTD/bin/node") $INTERP_SO"; missing=""
while [[ -n "$queue" ]]; do
  nq=""
  for so in $queue; do
    [[ -n "${seen[$so]:-}" ]] && continue; seen[$so]=1
    real="$(find_lib "$so")"; [[ -z "$real" ]] && { missing="$missing $so"; continue; }
    cp -L "$real" "$OUTD/lib/$so"; nq="$nq $(needed "$OUTD/lib/$so")"
  done
  queue="$nq"
done
[[ -z "${missing// }" ]] || { echo "ERROR: unresolved libs:$missing" >&2; exit 1; }
echo "    closure complete ($(ls "$OUTD/lib" | wc -l) libs), interpreter=$INTERP_SO"

echo "==> assembling rootfs-rooted payload tree"
PZ="$WORK/payload"; rm -rf "$PZ"
mkdir -p "$PZ/lib" "$PZ/opt/tessel/bin" "$PZ/opt/tessel/lib/node" "$PZ/usr/bin" "$PZ/usr/lib/node"
cp "$OUTD/bin/node" "$PZ/opt/tessel/bin/node"
cp -a "$OUTD/lib/." "$PZ/opt/tessel/lib/"
cp "$OUTD/lib/$INTERP_SO" "$PZ/lib/$INTERP_SO"          # PT_INTERP loader in /lib
cp "$R/usr/lib/node/tessel.js"        "$PZ/usr/lib/node/tessel.js"
cp "$R/usr/lib/node/tessel-export.js" "$PZ/usr/lib/node/tessel-export.js"
cp "$R/usr/lib/node/tessel.js"        "$PZ/opt/tessel/lib/node/tessel.js"
cp "$R/usr/lib/node/tessel-export.js" "$PZ/opt/tessel/lib/node/tessel-export.js"
cat > "$PZ/usr/bin/node" <<'WRAP'
#!/bin/sh
# Tessel factory node 4.2.1 (uClibc) isolated from the musl 25.12 rootfs.
# LD_LIBRARY_PATH is searched before /lib:/usr/lib, so the uClibc closure in
# /opt/tessel/lib resolves first (incl. the libstdc++.so.6 / libz.so.1 sonames
# that also exist as musl builds in /usr/lib) -> no ABI clash.
# NODE_PATH pins the tessel runtime dir: node derives its legacy global module
# path from execPath (/opt/tessel/bin/node -> /opt/tessel/lib/node), so without
# this require('tessel') would miss /usr/lib/node/tessel.js.
exec env LD_LIBRARY_PATH=/opt/tessel/lib \
         NODE_PATH="/usr/lib/node${NODE_PATH:+:$NODE_PATH}" \
         /opt/tessel/bin/node "$@"
WRAP
chmod 0755 "$PZ/usr/bin/node" "$PZ/opt/tessel/bin/node"

echo "==> writing $OUT"
tar czpf "$OUT" -C "$PZ" .
echo "    $(stat -c%s "$OUT") bytes"
sha256sum "$OUT"
